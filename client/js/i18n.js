// en+uk stay inline (en is t()'s fallback chain, uk is the tests' base and
// primary audience); the other nine load lazily -- see ensureLocale below.
export const SUPPORTED_LOCALES = ["en", "uk", "de", "es", "fr", "it", "ru", "lt", "lv", "et", "no"];

// Section A5/L4 (specs/phase5/lazy-loading.md): per-locale lazy dictionaries.
// Static import specifiers (not a computed template string) so the mapping
// stays greppable and no-bundler-safe. Cached; a failed import drops the
// cache so the next call retries (same policy as L1-L3).
const localeLoaders = {
  de: () => import("./locales/de.js"),
  es: () => import("./locales/es.js"),
  fr: () => import("./locales/fr.js"),
  it: () => import("./locales/it.js"),
  ru: () => import("./locales/ru.js"),
  lt: () => import("./locales/lt.js"),
  lv: () => import("./locales/lv.js"),
  et: () => import("./locales/et.js"),
  no: () => import("./locales/no.js")
};
const localePromises = {};

/**
 * Loads a lazy locale's dictionary into MESSAGES. Resolves immediately for
 * inline (en/uk), already-loaded, and unsupported locales -- callers decide
 * separately whether to setLocale afterwards.
 */
export function ensureLocale(locale) {
  if (MESSAGES[locale]) return Promise.resolve();
  const loader = localeLoaders[locale];
  if (!loader) return Promise.resolve();
  if (!localePromises[locale]) {
    localePromises[locale] = loader()
      .then((m) => {
        MESSAGES[locale] = m.default;
      })
      .catch((err) => {
        delete localePromises[locale];
        throw err;
      });
  }
  return localePromises[locale];
}

let activeLocale = "en";

export function getLocale() {
  return activeLocale;
}

export function setLocale(locale) {
  if (!MESSAGES[locale]) return; // unsupported -- keep the current locale
  activeLocale = locale;
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // storage unavailable (private mode etc.) -- locale still works for the session
  }
}

/**
 * Resolution order: explicit user choice (localStorage) -> browser language
 * (primary subtag, with nb/nn folded into no) -> en.
 */
export function detectLocale(browserLanguage) {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored && SUPPORTED_LOCALES.includes(stored)) return stored;
  } catch {
    // fall through to browser language
  }
  const primary = (browserLanguage || "").toLowerCase().split("-")[0];
  if (primary === "nb" || primary === "nn") return "no";
  return SUPPORTED_LOCALES.includes(primary) ? primary : "en";
}

export function t(key, params = {}) {
  const template = MESSAGES[activeLocale][key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

/**
 * Applies the active locale to static markup: elements with `data-i18n` get
 * their textContent replaced, `data-i18n-placeholder` sets the placeholder.
 */
export function applyTranslations(doc) {
  for (const element of doc.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.getAttribute("data-i18n"));
  }
  for (const element of doc.querySelectorAll("[data-i18n-placeholder]")) {
    element.setAttribute("placeholder", t(element.getAttribute("data-i18n-placeholder")));
  }
  // Icon-only controls: localize the tooltip and accessible name, not the content.
  for (const element of doc.querySelectorAll("[data-i18n-title]")) {
    const text = t(element.getAttribute("data-i18n-title"));
    element.setAttribute("title", text);
    element.setAttribute("aria-label", text);
  }
}
